#!/usr/bin/env python3
"""Build the ground vehicle model files from models/src/ground_units.py.

Zero external dependencies (Python standard library only): writes binary STL, a box manifest for
traceability, and an orthographic left-side preview PNG that can be compared with reference R1.

Usage:  python3 models/src/build_models.py [--out models/build]
"""
import argparse
import json
import os
import struct
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ground_units  # noqa: E402


def box_triangles(x0, y0, z0, x1, y1, z1):
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7),
             (0, 1, 5), (0, 5, 4), (3, 7, 6), (3, 6, 2),
             (0, 4, 7), (0, 7, 3), (1, 2, 6), (1, 6, 5)]
    return [(v[a], v[b], v[c]) for (a, b, c) in faces]


def write_stl(path, tri):
    with open(path, "wb") as fh:
        fh.write(b"battlefield ground vehicle - generated by models/src/build_models.py".ljust(80, b"\0"))
        fh.write(struct.pack("<I", len(tri)))
        for (a, b, c) in tri:
            ux, uy, uz = (b[0] - a[0], b[1] - a[1], b[2] - a[2])
            vx, vy, vz = (c[0] - a[0], c[1] - a[1], c[2] - a[2])
            nx, ny, nz = (uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx)
            n = (nx * nx + ny * ny + nz * nz) ** 0.5 or 1.0
            fh.write(struct.pack("<12fH", nx / n, ny / n, nz / n,
                                 a[0], a[1], a[2], b[0], b[1], b[2], c[0], c[1], c[2], 0))


def write_png(path, width, height, pixels):
    raw = bytearray()
    for y in range(height):
        raw.append(0)
        row = pixels[y]
        for x in range(width):
            r, g, b = row[x]
            raw.extend((r, g, b, 255))
    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    with open(path, "wb") as fh:
        fh.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
                 + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))


def side_preview(name, out, scale=3):
    """Orthographic left-side view: camera on -X looking +X, nose -Z drawn to the right."""
    boxes = ground_units.world_boxes(name)
    x0, y0, z0, x1, y1, z1 = ground_units.bounds(name)
    width = int((z1 - z0) * scale) + 20
    height = int((y1 - y0) * scale) + 20
    bg = (108, 132, 176)
    pixels = [[bg for _ in range(width)] for _ in range(height)]
    for (_, bx0, by0, bz0, bx1, by1, bz1) in sorted(boxes, key=lambda b: b[1], reverse=True):
        shade = 70 + int(60 * (1.0 - min(1.0, max(0.0, (bx1 - x0) / max(1.0, x1 - x0)))))
        colour = (shade, shade + 10, shade - 20)
        py0 = height - 10 - int((by1 - y0) * scale)
        py1 = height - 10 - int((by0 - y0) * scale)
        px0 = 10 + int((z0 * -1 + bz1 * -1) * -1 * scale) if False else 10 + int((bz0 - z0) * scale)
        px1 = 10 + int((bz1 - z0) * scale)
        # nose (-Z) to the right: mirror the Z axis
        mx0 = width - px1
        mx1 = width - px0
        for y in range(max(0, py0), min(height, py1)):
            for x in range(max(0, mx0), min(width, mx1)):
                pixels[y][x] = colour
    write_png(out, width, height, pixels)
    return width, height


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "build"))
    args = parser.parse_args()
    os.makedirs(args.out, exist_ok=True)
    manifest = {}
    for name in ground_units.VEHICLES:
        boxes = ground_units.world_boxes(name)
        tri = []
        for (_, x0, y0, z0, x1, y1, z1) in boxes:
            tri.extend(box_triangles(x0, y0, z0, x1, y1, z1))
        stl = os.path.join(args.out, name + ".stl")
        write_stl(stl, tri)
        bounds = ground_units.bounds(name)
        manifest[name] = {
            "boxes": len(boxes),
            "triangles": len(tri),
            "bounds_units": {"min": bounds[:3], "max": bounds[3:]},
            "bounds_blocks": [round((bounds[3] - bounds[0]) / 16.0, 3),
                              round((bounds[4] - bounds[1]) / 16.0, 3),
                              round((bounds[5] - bounds[2]) / 16.0, 3)],
            "parts": sorted({b[0].rsplit("_", 1)[0] if b[0][-1].isdigit() else b[0] for b in boxes}),
        }
        png = os.path.join(args.out, name + "_side.png")
        size = side_preview(name, png)
        print(f"{name}: boxes={len(boxes)} triangles={len(tri)} "
              f"blocks={manifest[name]['bounds_blocks']} -> {stl} + {png} {size}")
    with open(os.path.join(args.out, "box_manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=2)
    print("manifest ->", os.path.join(args.out, "box_manifest.json"))


if __name__ == "__main__":
    main()
